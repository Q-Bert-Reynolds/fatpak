// File names are code page 850 (FatFs's FF_CODE_PAGE: every Latin-1 letter, one byte each); the UI's
// text is Latin-1. Characters outside Latin-1 are ? on screen, and a name with one can't be typed.
#include "paths.h"

// code page 850's $80-$FF in Latin-1 (? where it has none)
static const unsigned char cp850[128] = {
  0xC7,0xFC,0xE9,0xE2,0xE4,0xE0,0xE5,0xE7,0xEA,0xEB,0xE8,0xEF,0xEE,0xEC,0xC4,0xC5,
  0xC9,0xE6,0xC6,0xF4,0xF6,0xF2,0xFB,0xF9,0xFF,0xD6,0xDC,0xF8,0xA3,0xD8,0xD7,0x3F,
  0xE1,0xED,0xF3,0xFA,0xF1,0xD1,0xAA,0xBA,0xBF,0xAE,0xAC,0xBD,0xBC,0xA1,0xAB,0xBB,
  0x3F,0x3F,0x3F,0x3F,0x3F,0xC1,0xC2,0xC0,0xA9,0x3F,0x3F,0x3F,0x3F,0xA2,0xA5,0x3F,
  0x3F,0x3F,0x3F,0x3F,0x3F,0x3F,0xE3,0xC3,0x3F,0x3F,0x3F,0x3F,0x3F,0x3F,0x3F,0xA4,
  0xF0,0xD0,0xCA,0xCB,0xC8,0x3F,0xCD,0xCE,0xCF,0x3F,0x3F,0x3F,0x3F,0xA6,0xCC,0x3F,
  0xD3,0xDF,0xD4,0xD2,0xF5,0xD5,0xB5,0xFE,0xDE,0xDA,0xDB,0xD9,0xFD,0xDD,0xAF,0xB4,
  0xAD,0xB1,0x3F,0xBE,0xB6,0xA7,0xF7,0xB8,0xB0,0xA8,0xB7,0xB9,0xB3,0xB2,0x3F,0xA0};

// a file name to Latin-1, at most count chars, returns the end (no 0)
char* ToLatin1(char* dest, const char* text, unsigned char count) {
  unsigned char c;
  while ((c = *text++) && count--) *dest++ = c >= 0x80 ? cp850[c - 0x80] : c;
  return dest;
}

// Latin-1 to a file name, with a 0
void ToFileName(char* dest, const char* text) {
  unsigned char c, i;
  while ((c = *text++)) {
    if (c >= 0x80) {
      for (i = 0; i != 128 && cp850[i] != c; ++i);
      c = i == 128 || c < 0xA0 ? '?' : 0x80 + i;
    }
    *dest++ = c;
  }
  *dest = 0;
}
