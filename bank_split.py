"""Splits SDCC's rgbds output for one C file across ROM0 and several ROMX sections, or EverDrive X OS
mode pages.

usage: python3 bank_split.py generated.asm banks.txt [--os]

banks.txt lists functions (without the leading underscore) per section, one section per line:
  ROM0: ld_16 ld_32 ...
  B: mount_volume f_write ...
Unlisted functions go in section A, data (tables, strings) goes in ROM0 so every bank can read it,
unless it's listed too (only the functions in its section can read it then).
These can be changed with "*: section" (unlisted functions), "DATA: section" and "THUNKS: section".
With --os, sections are ROM0, FIXED (ROMX bank 1, always mapped) or a page number (4-15, PAGE in
src/macros.asm), and data and thunks default to FIXED.
Calls and jumps between functions in different ROMX sections or pages, or from ROM0 to them, go
through thunks that use FarCallInline (src/far_call.asm).
"""
import re
import sys

SECTION_RE = re.compile(r'^\tSECTION FRAGMENT "([^"]+)",(\w+)')
FUNCTION_RE = re.compile(r'^; Function (\w+)')
LABEL_RE = re.compile(r'^(_\w+)::?$')
BRANCH_RE = re.compile(r'^(\t(?:call|jp)\s+(?:N?[ZC],\s*)?)(_\w+)(.*)$')
SPECIAL = ("*", "DATA", "THUNKS")


def read_config(path):
  dests = {}
  special = {}
  with open(path, encoding="utf8") as file:
    for line in file:
      line = line.split("#")[0].strip()
      if not line:
        continue
      dest, names = line.split(":", 1)
      dest = dest.strip()
      if dest in SPECIAL:
        special[dest] = names.strip()
        continue
      for name in names.split():
        dests["_" + name] = dest
  return dests, special


def main(asm_path, config_path, os_mode):
  with open(asm_path, encoding="utf8") as file:
    lines = file.read().split("\n")
  config, special = read_config(config_path)
  fixed = "FIXED" if os_mode else "ROM0"
  default = special.get("*", "A")
  data_dest = special.get("DATA", fixed)
  thunk_dest = special.get("THUNKS", fixed)
  near = ("ROM0", "FIXED")  # always mapped

  base = None
  functions = {}
  for line in lines:
    match = SECTION_RE.match(line)
    if match and match.group(1).endswith("_CODE"):
      base = match.group(1)[:-len("_CODE")]
    match = FUNCTION_RE.match(line)
    if match:
      functions["_" + match.group(1)] = None
  if base is None:
    return

  in_code = False
  for line in lines:
    match = SECTION_RE.match(line)
    if match:
      in_code = match.group(1).endswith("_CODE")
    match = FUNCTION_RE.match(line)
    if match and in_code:
      name = "_" + match.group(1)
      functions[name] = config.get(name, default)

  def section(dest):
    if dest == "ROM0":
      return f'\tSECTION FRAGMENT "{base} ROM0",ROM0'
    if os_mode and dest == "FIXED":
      return f'\tSECTION FRAGMENT "{base} FIXED",ROMX,BANK[1]'
    if os_mode:
      page = int(dest)
      return (f'\tSECTION FRAGMENT "Page {page}",ROMX,BANK[{page >> 1}]\n'
              f'\tLOAD FRAGMENT "Page {page} RAM",SRAM,BANK[{page}]')
    return f'\tSECTION FRAGMENT "{base} {dest}",ROMX'

  out = []
  thunks = set()
  in_code = False
  block = None
  dest = None
  for line in lines:
    match = SECTION_RE.match(line)
    if match:
      in_code = match.group(1).endswith("_CODE")
      if in_code and dest:
        line = section(dest)
      out.append(line)
      continue
    if in_code:
      match = FUNCTION_RE.match(line)
      label = LABEL_RE.match(line)
      if match:
        block = "_" + match.group(1)
        dest = functions[block]
        out.append(section(dest))
      elif label and label.group(1) != block:
        block = label.group(1)
        dest = functions.get(block) or config.get(block) or data_dest
        out.append(section(dest))
      branch = BRANCH_RE.match(line)
      if branch and dest:
        target = branch.group(2)
        target_dest = functions.get(target)
        if target_dest and target_dest not in near and target_dest != dest:
          thunks.add(target)
          line = branch.group(1) + target + "__far" + branch.group(3)
    out.append(line)

  out.append(";far call thunks generated by bank_split.py")
  out.append(section(thunk_dest))
  for target in sorted(thunks):
    out += [
      f"{target}__far:",
      "\tcall FarCallInline",
      f"\tDB BANK({target})",
      f"\tDW {target}",
    ]

  with open(asm_path, "w", encoding="utf8") as file:
    file.write("\n".join(out))

  counts = {}
  for name, where in functions.items():
    if where:
      counts[where] = counts.get(where, 0) + 1
  print(f"bank_split.py: {asm_path} {counts}, {len(thunks)} thunks")


if __name__ == "__main__":
  main(sys.argv[1], sys.argv[2], "--os" in sys.argv[3:])
