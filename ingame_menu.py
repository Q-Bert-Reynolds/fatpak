"""Compose the cart menu with the editor's VWF font and box geometry.

Static pixels are 1bpp; the menu applies DMG inversion or CGB highlighting at
runtime. The filename header is rendered before launching the game.
"""
from pathlib import Path
from data_file import db_bytes


def main():
  source = 'img/fonts/font_vwf.asm'
  glyphs = db_bytes(source, 'FontVWFGlyphs', 'FontVWFWidths')
  widths = db_bytes(source, 'FontVWFWidths')
  assert len(glyphs) == 256 * 8 and len(widths) == 256
  pixels = [[0] * 160 for _ in range(144)]

  def width(text):
    return sum(widths[ord(c)] for c in text)

  def text(x, y, label):
    assert x + width(label) <= 160
    for char in label:
      code = ord(char)
      for row in range(8):
        for bit in range(min(widths[code], 8)):
          pixels[y + row][x + bit] |= bool(glyphs[code * 8 + row] & (128 >> bit))
      x += widths[code]

  labels = ('Resume game', 'Save state', 'Load state', 'Return to OS')
  # Match Choose/OpenBox: leading space, four pixels padding, half-row ends.
  box_width = max(width(' ' + label) for label in labels) + 9
  left = (160 - box_width) // 2
  right = left + box_width - 1
  top, bottom = 52, 91
  for y in range(top, bottom + 1):
    pixels[y][left] = pixels[y][right] = 1
  for x in range(left, right + 1):
    pixels[top][x] = pixels[bottom][x] = 1
  for row, label in enumerate(labels):
    text(left + 4 + widths[32], 56 + row * 8, label)
  text(5, 136, 'A: select  B: resume')

  tiles = bytearray(8)  # tile 0 remains blank; tinted tiles are never shared
  first_col, last_col = left // 8, right // 8
  columns = last_col - first_col + 1
  maps = []
  row_tiles = {}
  for row in (6, 7, 8, 9, 10, 11, 17):
    start, end = (0, 20) if row == 17 else (first_col, last_col + 1)
    row_tiles[row] = len(tiles) // 8
    indices = []
    for column in range(start, end):
      indices.append(len(tiles) // 8)
      for y in range(row * 8, row * 8 + 8):
        tiles.append(sum(pixels[y][column * 8 + bit] << (7 - bit) for bit in range(8)))
    maps.append((0x9800 + row * 32 + start, indices))
  assert len(tiles) // 8 <= 96, 'Static tiles overlap the filename header'
  maps.append((0x9800, list(range(96, 116))))
  masks = [sum(128 >> bit for bit in range(8)
         if left < col * 8 + bit < right)
       for col in range(first_col, last_col + 1)]
  out = ['; generated by ingame_menu.py',
       f'DEF MENU_BOX_COLS EQU {columns}',
       *[f'DEF MENU_CHOICE{choice}_VRAM EQU ${0x8000 + row_tiles[7 + choice] * 16:04X}' for choice in range(4)],
       f'DEF MENU_FOOTER_VRAM EQU ${0x8000 + row_tiles[17] * 16:04X}',
       'END_PAGE', 'PAGE MENU_GRAPHICS_PAGE', 'MenuGraphics:', '  ld hl, MenuTiles', '  ld de, $8000',
       '  ld bc, MenuTilesEnd-MenuTiles', '.tile',
       '  ld a, [hli]', '  ld [de], a', '  inc de', '  ld [de], a', '  inc de',
       '  dec bc', '  ld a, b', '  or a, c', '  jr nz, .tile']
  for i, (address, indices) in enumerate(maps):
    out += [f'  ld hl, MenuMapRow{i}', f'  ld de, ${address:04X}',
        f'  ld bc, {len(indices)}', '  call MenuGraphicsCopy']
  out += ['  ret', 'MenuGraphicsCopy:', '  ld a, [hli]', '  ld [de], a',
      '  inc de', '  dec bc', '  ld a, b', '  or a, c',
      '  jr nz, MenuGraphicsCopy', '  ret', 'MenuTiles:']
  for offset in range(0, len(tiles), 8):
    out += ['  DB ' + ','.join(f'${v:02X}' for v in tiles[offset:offset + 8])]
  out += ['MenuTilesEnd:']
  for i, (_, indices) in enumerate(maps):
    out += [f'MenuMapRow{i}:', '  DB ' + ','.join(map(str, indices))]
  pixels = [[0] * 160 for _ in range(144)]
  text(5, 136, 'State unavailable / SD error')
  error = [sum(pixels[136+y][col*8+bit] << (7-bit) for bit in range(8)) for col in range(20) for y in range(8)]
  out += ['MenuError:', '  ld hl, MenuErrorTiles', '  ld de, MENU_FOOTER_VRAM', '  ld bc, 160', '.copy', '  ld a, [hli]', '  ld [de], a', '  inc de', '  ld [de], a', '  inc de', '  dec bc', '  ld a, b', '  or a, c', '  jr nz, .copy', '  ret', 'MenuErrorTiles:']
  for offset in range(0, len(error), 8):
    out += ['  DB ' + ','.join(f'${v:02X}' for v in error[offset:offset+8])]
  out += ['END_PAGE', 'PAGE INGAME_PAGE', 'MenuHighlightMasks:',
      '  DB ' + ','.join(f'${v:02X}' for v in masks), 'MenuBarMasks:',
      '  DS 20, $FF']
  Path('build').mkdir(exist_ok=True)
  Path('build/ingame_menu.asm').write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
  main()
