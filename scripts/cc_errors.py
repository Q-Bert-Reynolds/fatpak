"""Writes notes/CC_ERRORS.md: what each C ERROR number the Game Boy shows means (the codes of
modules/cc/cc_msg.h, the English of modules/cc/cc_msgs.c). usage: python3 scripts/cc_errors.py [--check]"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
CC = ROOT / 'modules/cc'

def text():
    codes = re.findall(r'^  (E_\w+)', (CC / 'cc_msg.h').read_text(), re.M)
    messages = re.findall(r'^  "((?:[^"\\]|\\.)*)",$', (CC / 'cc_msgs.c').read_text(), re.M)
    codes = [c for c in codes if c != 'E_COUNT']
    if len(codes) != len(messages): # E_NONE's empty string included
        sys.exit(f'cc_msg.h has {len(codes)} codes, cc_msgs.c {len(messages)} messages')
    rows = [f'| {n} | {m} |' for n, m in enumerate(messages) if n]
    return ('# C errors\n\n[Compiler](COMPILER.md)\n\n'
            'FILE > BUILD on a `.c` file shows `C ERROR <n>`, the line and the name it\'s about. The numbers are\n'
            '`modules/cc/cc_msg.h`\'s codes; the PC harness (`tests/cc_host.c`) prints these messages.\n'
            'Generated by `scripts/cc_errors.py`.\n\n| Code | Message |\n| --- | --- |\n' + '\n'.join(rows) + '\n')

def main():
    out = ROOT / 'notes/CC_ERRORS.md'
    new = text()
    if '--check' in sys.argv:
        if not out.exists() or out.read_text() != new:
            sys.exit('notes/CC_ERRORS.md is stale (run scripts/cc_errors.py)')
        return
    out.write_text(new)

if __name__ == '__main__':
    main()
