# Generates src/editor/keywords.asm, the code lexer's keyword tables (see TBLexCode)
# Each language has 32 buckets (project.gbp's few words are one list) indexed by a word's first char & 31, an entry is
# DB length, style << 4, then the word's chars, a bucket ends with 0. Asm words are lowercase
# (RGBDS is case insensitive), C words are case sensitive

C = {
  "STYLE_KEYWORD": """auto break case const continue default do else enum extern for goto if inline register
    restrict return sizeof static struct switch typedef union volatile while _Bool _Static_assert
    __asm __endasm __at __banked __nonbanked __naked __critical __interrupt __sfr __sbit
    __preserves_regs __sdcccall __reentrant __using""",
  "STYLE_TYPE": """char short int long float double void signed unsigned bool size_t
    int8_t int16_t int32_t uint8_t uint16_t uint32_t intptr_t uintptr_t ptrdiff_t FILE""",
  "STYLE_NUMBER": "true false NULL",
}

ASM = {
  "STYLE_KEYWORD": """adc add and bit call ccf cp cpl daa dec di ei halt inc jp jr ld ldh ldi ldd nop
    or pop push res ret reti rl rla rlc rlca rr rra rrc rrca rst sbc scf set sla sra srl stop sub swap xor""",
  "STYLE_TYPE": "a b c d e h l af bc de hl sp hli hld z nz nc",
  "STYLE_PREPROC": """def equ equs redef rb rw rs rsreset rsset section load endl union nextu endu
    db dw dl ds include incbin macro endm shift rept for endr break if elif else endc export
    purge assert static_assert fail warn print println opt pusho popo pushs pops charmap
    newcharmap setcharmap pushc popc align fragment rom0 romx vram sram wram0 wramx oam hram
    bank high low sizeof startof strlen strcat strsub strupr strlwr""",
}

# project.gbp (LANG_PROJECT, lexed as asm): its four words, one list without buckets
PROJECT = {"STYLE_PREPROC": "main output rgbasm rgbfix"}

def table(name, words, lower):
  buckets = [[] for _ in range(32)]
  seen = set()
  for style, text in words.items():
    for word in text.split():
      if lower: word = word.lower()
      if word in seen: continue # the first style wins (set is an instruction)
      seen.add(word)
      buckets[ord(word[0]) & 31].append((word, style))
  out = [f"{name}:\n"]
  out += [f"  DW {name}{i}\n" if b else f"  DW {name}None\n" for i, b in enumerate(buckets)]
  for i, b in enumerate(buckets):
    if not b: continue
    out.append(f"{name}{i}:\n")
    for word, style in sorted(b):
      out.append(f'  DB {len(word)}, {style} << 4, "{word}"\n')
    out.append("  DB 0\n")
  out.append(f"{name}None: DB 0\n")
  return "".join(out)

def main():
  longest = max(len(w) for d in (C, ASM, PROJECT) for t in d.values() for w in t.split())
  with open("src/editor/keywords.asm", "w", encoding="utf8") as f:
    f.write("; generated by keywords.py\n")
    f.write(f"DEF KEYWORD_MAX EQU {longest};longest word\n\n")
    f.write('  KEYWORDS_SECTION;with KeywordLookup\n\n')
    f.write(table("KeywordsC", C, False))
    f.write("\n")
    f.write(table("KeywordsAsm", ASM, True))
    f.write("\nKeywordsProject:\n")
    for style, text in PROJECT.items():
      for word in text.split():
        f.write(f'  DB {len(word)}, {style} << 4, "{word}"\n')
    f.write("  DB 0\n")

if __name__ == "__main__":
  main()
